package com.chessinsight.chessinsight.chess;

import com.github.bhlangonijr.chesslib.Board;
import com.github.bhlangonijr.chesslib.move.Move;
import com.github.bhlangonijr.chesslib.move.MoveList;
import jakarta.annotation.PostConstruct;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Service;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

@Service
public class OpeningClassifier {

    private final Map<String, OpeningLine> openingsByPosition =
        new HashMap<>();

    @PostConstruct
    public void loadOpenings() {
        String[] files = {
            "a.tsv",
            "b.tsv",
            "c.tsv",
            "d.tsv",
            "e.tsv"
        };

        for (String file : files) {
            loadFile(file);
        }

        System.out.println(
            "Loaded " + openingsByPosition.size()
                + " opening positions"
        );
    }

    private void loadFile(String fileName) {
        ClassPathResource resource =
            new ClassPathResource("openings/" + fileName);

        try (BufferedReader reader = new BufferedReader(
            new InputStreamReader(
                resource.getInputStream(),
                StandardCharsets.UTF_8))) {

            String line;
            boolean firstLine = true;

            while ((line = reader.readLine()) != null) {
                if (firstLine && line.startsWith("eco\t")) {
                    firstLine = false;
                    continue;
                }

                firstLine = false;

                if (line.isBlank()) {
                    continue;
                }

                String[] columns = line.split("\t", 3);

                if (columns.length != 3) {
                    continue;
                }

                String eco = columns[0].trim();
                String name = columns[1].trim();
                String pgnMoves = columns[2].trim();

                try {
                    MoveList moveList = new MoveList();
                    moveList.loadFromSan(pgnMoves);

                    if (moveList.isEmpty()) {
                        continue;
                    }

                    Board board = new Board();

                    for (Move move : moveList) {
                        board.doMove(move);
                    }

                    String positionKey = getPositionKey(board);

                    OpeningLine opening =
                        new OpeningLine(eco, name, moveList.size());

                    openingsByPosition.merge(
                        positionKey,
                        opening,
                        (existing, candidate) ->
                            candidate.moveCount() > existing.moveCount()
                                ? candidate
                                : existing
                    );

                } catch (RuntimeException e) {
                    throw new IllegalStateException(
                        "Could not parse opening '" + name
                            + "' from " + fileName,
                        e
                    );
                }
            }

        } catch (IOException e) {
            throw new IllegalStateException(
                "Could not load opening file: " + fileName,
                e
            );
        }
    }

    public String classify(List<Move> gameMoves) {
        Board board = new Board();


        for (Move move : gameMoves) {
            board.doMove(move);
        }


        for (int i = gameMoves.size() - 1; i >= 0; i--) {
            OpeningLine match =
                openingsByPosition.get(getPositionKey(board));

            if (match != null) {
                return match.name();
            }

            board.undoMove();
        }

        return null;
    }

    private String getPositionKey(Board board) {
        String fen = board.getFen();
        String[] fields = fen.trim().split("\\s+");


        if (fields.length < 4) {
            throw new IllegalStateException(
                "Invalid FEN generated by chesslib: " + fen
            );
        }

        return String.join(
            " ",
            Arrays.copyOfRange(fields, 0, 4)
        );
    }

    private record OpeningLine(
        String eco,
        String name,
        int moveCount
    ) {
    }
}